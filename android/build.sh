#!/bin/bash
# Builds the companion APK without Gradle: aapt2 -> javac -> d8 -> zipalign -> apksigner.
#
# Toolchain, first match wins:
#   JDK          $JAVA_HOME, ../tools/jdk-linux (WSL), ../tools/jdk/Contents/Home (Mac)
#   build-tools  $ANDROID_HOME/build-tools/34.0.0, ../tools/sdk/build-tools/34.0.0, ../tools/android-14
#   android.jar  $ANDROID_HOME/platforms/android-34, ../tools/sdk/platforms/android-34
# On a fresh machine, WINDOWS.md has the two downloads that fill ../tools.
set -euo pipefail
cd "$(dirname "$0")"
TOOLS=../tools

first_dir() { for d in "$@"; do [ -n "$d" ] && [ -d "$d" ] && { (cd "$d" && pwd); return; }; done; return 1; }

JAVA_HOME="$(first_dir "${JAVA_HOME:-}" $TOOLS/jdk-linux $TOOLS/jdk/Contents/Home)" \
  || { echo "no JDK: set JAVA_HOME or unpack one into $TOOLS/jdk-linux" >&2; exit 1; }
export JAVA_HOME
PATH="$JAVA_HOME/bin:$PATH"
SDK="${ANDROID_HOME:-$TOOLS/sdk}"
BT="$(first_dir "$SDK/build-tools/34.0.0" $TOOLS/sdk/build-tools/34.0.0 $TOOLS/android-14)" \
  || { echo "no build-tools 34: sdkmanager \"build-tools;34.0.0\"" >&2; exit 1; }
PLATFORM="$(first_dir "$SDK/platforms/android-34" $TOOLS/sdk/platforms/android-34)" \
  || { echo "no platform 34: sdkmanager \"platforms;android-34\"" >&2; exit 1; }
ANDROID_JAR="$PLATFORM/android.jar"
OUT=build
rm -rf $OUT/classes $OUT/gen $OUT/*.apk.tmp && mkdir -p $OUT/classes $OUT/gen/com/shrey/usagedump

# A debug keystore, generated once. The APK only ever runs on your own phone.
# A new keystore cannot update an APK signed by another one: uninstall first.
if [ ! -f debug.keystore ]; then
  keytool -genkeypair -keystore debug.keystore -storepass android -keypass android \
    -alias debug -keyalg RSA -keysize 2048 -validity 10000 \
    -dname "CN=Usage Dump Debug" >/dev/null 2>&1
fi

# The Drive OAuth client (DRIVE_SETUP.md). Kept out of git; without it the app
# still collects, it just has nothing to sign in with.
CLIENT_ID="" CLIENT_SECRET=""
if [ -f oauth.properties ]; then
  CLIENT_ID="$(sed -n 's/^client_id=//p' oauth.properties | tr -d '[:space:]')"
  CLIENT_SECRET="$(sed -n 's/^client_secret=//p' oauth.properties | tr -d '[:space:]')"
fi
[ -n "$CLIENT_ID" ] || echo "note: no android/oauth.properties -- building without Drive upload"
cat > $OUT/gen/com/shrey/usagedump/Secrets.java <<EOF
package com.shrey.usagedump;

/** Generated by build.sh from oauth.properties. Do not edit. */
final class Secrets {
    static final String CLIENT_ID = "$CLIENT_ID";
    static final String CLIENT_SECRET = "$CLIENT_SECRET";
}
EOF

"$BT/aapt2" link -I "$ANDROID_JAR" --manifest AndroidManifest.xml -o $OUT/base.apk
javac -source 8 -target 8 -nowarn -Xlint:-options -bootclasspath "$ANDROID_JAR:$BT/core-lambda-stubs.jar" -classpath "$ANDROID_JAR" \
  -d $OUT/classes $(find src $OUT/gen -name '*.java')
"$BT/d8" --lib "$ANDROID_JAR" --min-api 26 --output $OUT $(find $OUT/classes -name '*.class')
(cd $OUT && zip -q base.apk classes.dex)
"$BT/zipalign" -f 4 $OUT/base.apk $OUT/aligned.apk
"$BT/apksigner" sign --ks debug.keystore --ks-pass pass:android --key-pass pass:android \
  --out $OUT/usagedump.apk $OUT/aligned.apk
rm -f $OUT/base.apk $OUT/aligned.apk $OUT/classes.dex $OUT/usagedump.apk.idsig
echo "built: $(cd $OUT && pwd)/usagedump.apk"
